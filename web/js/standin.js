/** Resolve symbolic tokens without depending on their truncated label. */
export function standInName(text, byte, codec) {
  if ([...text].length === 1) return text;
  const ch = [...codec.chars].find(([, b]) => b === byte)?.[0];
  if (ch) return ch;
  const name = Object.keys(codec.named).find((k) => parseInt(codec.named[k], 16) === byte);
  return NAMED[name] ?? LIGATURE[name] ?? "?";
}

/** Approximate 16x16 ink and shadow; widths remain untouched. */
export function standIn(text, width, small = false, aliases = {}) {
  const px = new Uint8Array(256);
  const room = Math.max(1, Math.min(15, width - 1));
  const key = aliases[text] ?? text;
  const [base, accent] = [...key.normalize("NFD")];
  let rows;
  let top;
  if (key.length > 1 && LIGATURES.has(key)) {
    const parts = [...key].map((ch) => (MINI[ch] ?? MINI.E).split("/"));
    const height = Math.max(...parts.map((p) => p.length));
    rows = Array.from({ length: height }, (_, y) => parts.map((p) => p[y] ?? ".".repeat(p[0].length)).join("."));
    top = 10 - height + 1;
  } else if (base in LETTERS || base in DIGITS) {
    rows = (LETTERS[base] ?? DIGITS[base]).split("/");
    if (accent && base === "i") rows[0] = ".";
    const descender = "gpqy".includes(base);
    top = 11 - rows.length + (descender ? 2 : 0);
    if (base === "j") top = 4;
    // Main capitals are one row taller than small capitals.
    if (!small && /[A-Z0-9]/.test(base)) { rows.splice(3, 0, rows[3]); top--; }
  } else {
    [rows, top] = SYMBOLS[key] ?? SYMBOLS["?"];
    rows = rows.split("/");
  }
  const shift = small ? -1 : 0;
  const put = (x, y) => { if (x >= 0 && x < room && y >= 0 && y < 15) px[y * 16 + x] = INK; };
  const sourceWidth = Math.max(...rows.map((r) => r.length));
  const scale = Math.min(1, room / sourceWidth);
  rows.forEach((r, y) => [...r].forEach((v, x) => { if (v === "#") put(Math.floor(x * scale), top + shift + y); }));
  if (accent) {
    const marks = { "\u0300": "#./.#", "\u0301": ".#/#.", "\u0302": ".#./#.#", "\u0308": "#.#", "\u0303": ".#.#/#.#.", "\u0327": ".#/#." };
    const mark = marks[accent];
    if (mark) mark.split("/").forEach((r, y) => [...r].forEach((v, x) => {
      if (v === "#") put(x, accent === "\u0327" ? 12 + shift + y : top + shift - 3 + y);
    }));
  }
  for (let y = 14; y >= 0; y--) for (let x = room - 1; x >= 0; x--) if (px[y * 16 + x] === INK) {
    for (const [dx, dy] of [[1, 0], [0, 1], [1, 1]]) {
      const at = (y + dy) * 16 + x + dx;
      if (px[at] !== INK) px[at] = SHADOW;
    }
  }
  return px;
}
