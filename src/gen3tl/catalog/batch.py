"""Translation batches for the review workflow: export, import, review state and approval."""

from __future__ import annotations


import json
import re
from pathlib import Path

from . import entrynotes, keys
from .catalog import load_catalog
from .po import catalog_name, read, translation_state, write

PASSES = ("accuracy", "proofreading", "editorial")
BATCH_ROOT = Path("translation/batches")
PREFILL_HEADING = "## Pre-filled from approved translations"


def translation_value(value) -> tuple[str, str]:
    """Read explicit states or legacy text drafts."""
    if isinstance(value, str):
        return value, "text" if value else "empty"
    if not isinstance(value, dict) or set(value) != {"translation", "state"}:
        raise ValueError("a translation draft needs text and state")
    text, state = value["translation"], value["state"]
    return text, translation_state(text, state)


def translated_text(value, english: str) -> str | None:
    """Resolve inherited text for review checks."""
    if value is None:
        return None
    text, state = translation_value(value)
    return english if state == "original" else text


def approved_by_english(catalog: dict, english=None) -> dict[str, dict[str, list[str]]]:
    """English of approved entries -> translated texts -> ids; approved means translated and not fuzzy."""
    out: dict[str, dict[str, list[str]]] = {}
    for sid, (p, e) in catalog.items():
        source = e.msgid if english is None else english(sid, e)
        if source and (e.msgstr or "empty" in e.flags) and not e.fuzzy:
            out.setdefault(source, {}).setdefault(e.msgstr, []).append(sid)
    return out


def prefill(ids: list[str], catalog: dict, approved: dict | None = None) -> tuple[dict, dict]:
    """Drafts for the ids whose English matches approved entries."""
    approved = approved_by_english(catalog) if approved is None else approved
    filled, variants = {}, {}
    for sid in ids:
        texts = {translated: [i for i in src if i != sid] for translated, src in approved.get(catalog[sid][1].msgid, {}).items()}
        texts = {translated: src for translated, src in texts.items() if src}
        if len(texts) == 1:
            filled[sid] = next(iter(texts.items()))
        elif texts:
            variants[sid] = texts
    return filled, variants


def prefill_notes(filled: dict, variants: dict, catalog: dict, po_root: Path) -> str:
    """The generated translator-notes.md section for a pre-filled batch."""
    key = keys.for_catalog(catalog).key

    def where(sid: str) -> str:
        p = catalog[sid][0]
        try:
            p = p.relative_to(po_root)
        except ValueError:
            pass
        return f"{key(sid)} ({p.with_suffix('').as_posix()})"

    lines = [PREFILL_HEADING, "",
             "Generated by `catalog batch-export --prefill`; replaced on the next pre-filled export. Each pre-filled",
             "entry in translation.json repeats the approved translation of the entries with the same English.",
             "It is a draft: for each one check the speaker's gender, the addressee and",
             "the form of address, the words inserted into its {STR_VAR_n}, and the fit in its window, and",
             "change it where this entry's context needs a different translation. Entries left null",
             "have no single approved match and are translated as usual; null never imports.", "",
             f"### Pre-filled entries ({len(filled)})", ""]
    lines += [f"- {key(sid)} from {', '.join(where(i) for i in src)}"
              for sid, (translated, src) in filled.items()] or ["None."]
    lines += ["", f"### Several approved variants, left empty ({len(variants)})", ""]
    for sid, texts in variants.items():
        lines.append(f"- {key(sid)}, English {json.dumps(catalog[sid][1].msgid, ensure_ascii=False)}:")
        lines += [f"  - {json.dumps(translated, ensure_ascii=False)} in {', '.join(where(i) for i in src)}"
                  for translated, src in texts.items()]
    if not variants:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def put_section(path: Path, section: str) -> None:
    """Write a Markdown section (starting with its "## " heading) into a file, replacing an earlier copy."""
    old = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    new = section.rstrip("\n").splitlines()
    if new[0] in old:
        a = old.index(new[0])
        b = next((k for k in range(a + 1, len(old)) if old[k].startswith("## ")), len(old))
        out = old[:a] + new + ([""] + old[b:] if b < len(old) else [])
    else:
        out = old + ([""] if old and old[-1] else []) + new
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def record_speakers(rules: list[dict], rom, inv: dict) -> dict[str, list[str]]:
    """Entry id -> context lines naming the speaker of a record text ([[context.record_speakers]])."""
    classes = {e["index"]: e["text"] for e in inv["entries"]
               if e.get("kind") == "fixed" and e.get("table") == "trainer_classes"}
    by_at: dict[int, str] = {}
    for rule in rules:
        for i in range(rule["count"]):
            rec = rule["base"] + i * rule["stride"]
            g = rom.u8(rec + rule["gender_at"])
            gender = rule["genders"][g] if g < len(rule["genders"]) else f"unknown ({g})"
            bits = [f"speaker: {gender}"]
            if "class_at" in rule:
                c = rom.u8(rec + rule["class_at"])
                bits.append(f"trainer class {c}" + (f" ({classes[c]})" if c in classes else ""))
            note = ", ".join(bits) + f" (record {i} of {rule['name']})"
            for f in rule["fields"]:
                by_at.setdefault(rec + f, note)
    out: dict[str, list[str]] = {}
    for e in inv["entries"]:
        for r in e["refs"]:
            if r["at"] in by_at and by_at[r["at"]] not in out.get(e["id"], []):
                out.setdefault(e["id"], []).append(by_at[r["at"]])
    return out


def export_batch(name: str, ids: list[str], po_root: Path, limits: dict, matcher=None,
                 root: Path = BATCH_ROOT, force: bool = False, prefill_drafts: bool = False,
                 notes: dict[str, list[str]] | None = None) -> Path:
    """Write a review batch directory and return its path."""
    status = root / name / "status.json"
    if not force and status.exists() and json.loads(status.read_text(encoding="utf-8")).get("approved"):
        # an approved batch's files record its review
        raise ValueError(f"batch {name} is approved; exporting would overwrite it (use --force)")
    if not force and (root / name / "translation.json").exists():
        # keep the source its translation and reviews used
        raise ValueError(f"batch {name} has a translation; exporting would replace its source (use --force)")
    if prefill_drafts and (root / name / "translation.json").exists():
        # --force replaces the source, never the translation
        raise ValueError(f"batch {name} has a translation; a pre-fill would replace it")
    catalog = load_catalog(po_root)
    aliases = keys.for_profile(None) or keys.for_catalog(catalog)
    ids = [aliases.entry_id(sid) for sid in ids]   # a key, an inventory id or an offset
    out = []
    for sid in ids:
        if sid not in catalog:
            raise KeyError(f"{aliases.key(sid)} not in the catalog")
        p, e = catalog[sid]
        lim = limits.get(sid)
        item = {
            "id": aliases.key(sid), "file": catalog_name(p), "source_text": e.msgid,
            "context": e.extracted + (notes or {}).get(sid, []),
            "limit": None if lim is None else {k: v for k, v in vars(lim).items() if v is not None},
            "current": e.msgstr,
            "current_state": e.state,
            "note": e.source_note,
        }
        # Inserted words retain their current translations.
        inserted = []
        for c in e.extracted:
            m = re.match(r"(\{STR_VAR_\d\}) may be (\S+?): ", c)
            if m and aliases.entry_id(m.group(2)) in catalog:
                w = catalog[aliases.entry_id(m.group(2))][1]
                inserted.append({"slot": m.group(1), "id": aliases.key(m.group(2)), "source_text": w.msgid,
                                 "translation": w.msgstr})
        if inserted:
            item["inserted_words"] = inserted
        if matcher is not None:
            terms = []
            for t in matcher.in_source(e.msgid):
                if t.id not in {x["id"] for x in terms}:
                    terms.append({"id": t.id, "category": t.category, "source_text": t.source_text,
                                  "translation": t.translation, "label": t.label, "gender": t.gender,
                                  "address": t.address,
                                  "forms": {k: v for k, v in t.forms.items() if k.endswith("sing")}})
            item["glossary"] = terms
        out.append(item)
    d = root / name
    d.mkdir(parents=True, exist_ok=True)
    (d / "source.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    status = d / "status.json"
    st = json.loads(status.read_text(encoding="utf-8")) if status.exists() else {"name": name, "approved": False}
    st["entries"] = len(out)  # re-exports refresh the count
    st.pop("prefill", None)
    if prefill_drafts:  # drafts from approved translations of the same English
        filled, variants = prefill(ids, catalog)
        # "" is an intended empty translation, so null marks open
        tr = {aliases.key(sid): filled[sid][0] if sid in filled else None for sid in ids}   # null: untranslated
        (d / "translation.json").write_text(json.dumps(tr, ensure_ascii=False, indent=1), encoding="utf-8")
        put_section(d / "translator-notes.md", prefill_notes(filled, variants, catalog, po_root))
        st["prefill"] = {"filled": len(filled), "variants": len(variants)}
    status.write_text(json.dumps(st, indent=1, ensure_ascii=False), encoding="utf-8")
    return d


def import_path(source: str, po_root: Path) -> Path:
    """Resolve a recorded catalog path inside the selected import root."""
    directory, original = po_root.resolve(), Path(source)
    try:
        relative = original.resolve().relative_to(directory)
    except ValueError:
        parts = original.parts
        prefixes = [i for i in range(len(parts) - 1) if parts[i:i + 2] == ("translation", "po")]
        if not prefixes:
            raise ValueError(f"batch source is outside the catalog: {source}")
        relative = Path(*parts[prefixes[-1] + 2:])
    destination = (directory / relative).resolve()
    if not destination.is_relative_to(directory):
        raise ValueError(f"batch source escapes the selected catalog: {source}")
    return destination


def batch_aliases(po_root: Path) -> keys.Aliases:
    """The keys of the effective profile, else those the catalog carries."""
    return keys.for_profile(None) or keys.for_catalog(load_catalog(po_root))


def import_batch(name: str, po_root: Path, root: Path = BATCH_ROOT) -> dict:
    d = root / name
    aliases = batch_aliases(po_root)
    key = aliases.key   # batches name entries by key or inventory id
    tr = {key(k): v for k, v in json.loads((d / "translation.json").read_text(encoding="utf-8")).items()}
    src = {key(x["id"]): x for x in json.loads((d / "source.json").read_text(encoding="utf-8"))}
    unknown = [k for k in tr if k not in src]
    if unknown:
        raise KeyError(f"translation.json has ids outside the batch: {unknown[:5]}")
    untranslated = [k for k, v in tr.items() if v is None]
    if untranslated:  # a pre-filled batch marks open entries with null
        raise ValueError(f"translation.json has untranslated (null) entries: {untranslated[:5]}")
    tr = {sid: translation_value(value) for sid, value in tr.items()}
    from ..build.keyboard import reject_owned
    reject_owned({aliases.entry_id(k): v for k, v in tr.items()})
    by_file: dict[Path, dict[str, tuple[str, str]]] = {}
    for sid, value in tr.items():
        destination = import_path(src[sid]["file"], po_root)
        by_file.setdefault(destination, {})[sid] = value
    changed = 0
    for f, items in by_file.items():
        hdr, es = read(Path(f), notes_path=entrynotes.path(po_root))
        for e in es:
            if key(e.msgctxt) not in items:
                continue
            changed += e.set_translation(*items[key(e.msgctxt)])
        write(Path(f), es, hdr, notes_path=entrynotes.path(po_root))
    return {"entries": len(tr), "changed": changed, "missing": [k for k in src if k not in tr]}


def review_state(name: str, root: Path = BATCH_ROOT) -> dict:
    """Latest round per pass and its finding count."""
    d = root / name
    state = {}
    for p in PASSES:
        rounds = sorted(d.glob(f"review-{p}-*.json"), key=lambda x: int(x.stem.rsplit("-", 1)[1]))
        if rounds:
            findings = json.loads(rounds[-1].read_text(encoding="utf-8"))
            state[p] = {"round": int(rounds[-1].stem.rsplit("-", 1)[1]), "findings": len(findings)}
        else:
            state[p] = {"round": 0, "findings": None}
    return state


def approve_batch(name: str, po_root: Path, root: Path = BATCH_ROOT) -> dict:
    state = review_state(name, root)
    open_passes = [p for p, s in state.items() if s["findings"] != 0]
    if open_passes:
        raise RuntimeError(f"batch {name} not clean: {open_passes} ({state})")
    d = root / name
    key = batch_aliases(po_root).key
    ids = {key(x["id"]) for x in json.loads((d / "source.json").read_text(encoding="utf-8"))}
    drafts = d / "translation.json"
    originals = {key(sid) for sid, value in json.loads(drafts.read_text()).items()
                 if isinstance(value, dict) and translation_value(value) == ("", "original")} if drafts.exists() else set()
    cleared = 0
    files = {import_path(x["file"], po_root)
             for x in json.loads((d / "source.json").read_text(encoding="utf-8"))}
    for f in sorted(files):
        hdr, es = read(Path(f), notes_path=entrynotes.path(po_root))
        for e in es:
            if (key(e.msgctxt) in ids and e.fuzzy
                    and (e.state != "original" or key(e.msgctxt) in originals)):
                e.set_fuzzy(False)
                cleared += 1
        write(Path(f), es, hdr, notes_path=entrynotes.path(po_root))
    status = json.loads((d / "status.json").read_text(encoding="utf-8"))
    status.update({"approved": True, "reviews": state})
    (d / "status.json").write_text(json.dumps(status, indent=1, ensure_ascii=False), encoding="utf-8")
    return {"cleared_fuzzy": cleared, "reviews": state}
